const toIso = (v) => (v ? new Date(v).toISOString() : null);

const jobFromRow = (r) => ({
  id: r.id,
  number: Number(r.number),
  customerName: r.customer_name,
  customerPhone: r.customer_phone || "",
  customerEmail: r.customer_email || "",
  customerAddress: r.customer_address || "",
  trade: r.trade,
  // Component trades when the project type mentioned more than one. Always
  // populated (a single-trade job gets a one-element array) so reporting never
  // has to special-case combo.
  trades: Array.isArray(r.trades) && r.trades.length ? r.trades : (r.trade ? [r.trade] : []),
  isRepair: Boolean(r.is_repair),
  // Renew / Rehab / Yoak PM, from the job_types registry. The database fills it
  // when an insert leaves it blank (from the name), and a name containing
  // "Yoak PM" always means yoak_pm. Only admins can change it (guard trigger).
  jobType: r.job_type || "renew",
  // How the job came in: "manual" (entered here), "webhook" (a GHL contract),
  // "system", or null for jobs created before 2026-11-18. Set by the database.
  createdVia: r.created_via || null,
  // Chosen by hand once the job is paid in full: "in_progress" | "completed" | "".
  paidStatus: r.paid_status || "",
  stage: r.stage,
  // Stage is the board column; substage and flag are facts about the job that
  // the column cannot express. See map_ghl_inbound in the database.
  substage: r.substage || "",
  flag: r.flag || "",
  // GoHighLevel's opportunity status, separate from the board stage. Only
  // 'open' jobs are managed by the sync; the rest are kept as history.
  ghlStatus: r.ghl_status || "open",
  ghlProjectDisplayId: r.ghl_project_display_id || null,
  // Read-only. A job whose contact came from a GHL opportunity (a monitored
  // pipeline) shows that contact's GHL notes; see JobNotes in App.jsx.
  ghlContactId: r.ghl_contact_id || null,
  ghlOpportunityId: r.ghl_opportunity_id || null,
  // Jobs that belong to one customer project (phases, add-ons, a re-sell after
  // a cancellation) share a group. Set automatically when two jobs carry the
  // same GHL project #, or by hand with linkJobs(). Each job keeps its own
  // contract, payments and stage.
  groupId: r.group_id || null,
  contractAmount: Number(r.contract_amount || 0),
  startDate: toIso(r.start_date),
  targetDate: toIso(r.target_date),
  // Calendar dates, not instants — passed through as "YYYY-MM-DD" rather than
  // via toIso(), which would make them timezone-sensitive and shift the day.
  contractSignedDate: r.contract_signed_date || null,
  materialsOrderedDate: r.materials_ordered_date || null,
  // When the opportunity was created in GoHighLevel. Read-only here; it is what
  // the signed date was seeded from.
  ghlCreatedAt: toIso(r.ghl_created_at),
  notes: r.notes || "",
  createdAt: toIso(r.created_at),
  clientPayments: [],
  // Client credits: money taken off what the client owes after signing (its own
  // table, never mixed into clientPayments). Stored positive, shown negative.
  // Admin-only by RLS, so always empty for a project manager.
  clientCredits: [],
  vendorPayments: [],
  // Vendor credits: money a vendor takes back off this job's cost (credit memo,
  // returned materials). Own table, stored positive, shown negative; lowers
  // vendor cost and never counts as cash. Admin-only by RLS.
  vendorCredits: [],
  // Project manager / installers / services working this job. Filled by
  // loadAll from job_assignments; the calendar reads the same rows.
  assignments: [],
  // The most recent GP finalization, when the office has taken one. Null on
  // every job nobody has finalized, and on every job for a project manager,
  // whose RLS returns no rows from that table at all.
  finalization: null,
});

const jobToRow = (j) => {
  const row = {};
  if (j.customerName !== undefined) row.customer_name = j.customerName;
  if (j.customerPhone !== undefined) row.customer_phone = j.customerPhone || "";
  if (j.customerEmail !== undefined) row.customer_email = j.customerEmail || "";
  if (j.customerAddress !== undefined) row.customer_address = j.customerAddress || "";
  if (j.trade !== undefined) {
    row.trade = j.trade;
    // Assigning a single trade by hand replaces any combo breakdown — the
    // person picking from the dropdown is stating what the job actually is.
    if (j.trades === undefined) row.trades = j.trade ? [j.trade] : [];
  }
  if (j.trades !== undefined) row.trades = j.trades;
  if (j.isRepair !== undefined) row.is_repair = Boolean(j.isRepair);
  if (j.jobType !== undefined) row.job_type = j.jobType || null;
  // The GHL project # is the key that lets an incoming GHL contract attach to
  // this job instead of creating a second one. Digits only; blank clears it.
  if (j.ghlProjectDisplayId !== undefined) {
    const digits = String(j.ghlProjectDisplayId || "").replace(/\D/g, "");
    row.ghl_project_display_id = digits || null;
  }
  if (j.paidStatus !== undefined) row.paid_status = j.paidStatus || null;
  if (j.stage !== undefined) row.stage = j.stage;
  if (j.substage !== undefined) row.substage = j.substage || null;
  if (j.flag !== undefined) row.flag = j.flag || null;
  if (j.ghlStatus !== undefined) row.ghl_status = j.ghlStatus;
  if (j.contractAmount !== undefined) row.contract_amount = Number(j.contractAmount) || 0;
  if (j.startDate !== undefined) row.start_date = toIso(j.startDate);
  if (j.targetDate !== undefined) row.target_date = toIso(j.targetDate);
  // Written as bare "YYYY-MM-DD" (or null when cleared). No toIso(): a date
  // column has no timezone, and converting would move it a day.
  if (j.contractSignedDate !== undefined) row.contract_signed_date = j.contractSignedDate || null;
  if (j.materialsOrderedDate !== undefined) row.materials_ordered_date = j.materialsOrderedDate || null;
  if (j.notes !== undefined) row.notes = j.notes || "";
  return row;
};

