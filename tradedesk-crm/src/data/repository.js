import { supabase, isSupabaseConfigured } from "./supabaseClient.js";
import { localAdapter } from "./localAdapter.js";

/**
 * The single persistence boundary for TradeDesk.
 *
 * The UI in App.jsx works with one nested in-memory shape:
 *
 *   { jobs: [ { ...job, clientPayments: [], vendorPayments: [] } ], vendors: [] }
 *
 * Postgres stores that as four related tables (jobs, vendors, client_payments,
 * vendor_payments). This module is the only place that knows about both — it
 * assembles the nested shape on load and writes single rows on mutation.
 *
 * Writing single rows (rather than re-saving one big JSON blob) is the whole
 * point of the relational move: two people editing different jobs at the same
 * time no longer overwrite each other.
 *
 * Every mutator takes an id generated by the caller (crypto.randomUUID) so the
 * UI can update optimistically and still match the row the database ends up
 * holding.
 */

const LOCAL_KEY = "tradedesk-job-tracker-v1";

/* ---------------------------------------------------------------------------
   row <-> app-object mapping
   --------------------------------------------------------------------------- */

const toIso = (v) => (v ? new Date(v).toISOString() : null);

const jobFromRow = (r) => ({
  id: r.id,
  number: Number(r.number),
  customerName: r.customer_name,
  customerPhone: r.customer_phone || "",
  customerEmail: r.customer_email || "",
  customerAddress: r.customer_address || "",
  trade: r.trade,
  stage: r.stage,
  contractAmount: Number(r.contract_amount || 0),
  startDate: toIso(r.start_date),
  targetDate: toIso(r.target_date),
  notes: r.notes || "",
  createdAt: toIso(r.created_at),
  clientPayments: [],
  vendorPayments: [],
});

const jobToRow = (j) => {
  const row = {};
  if (j.customerName !== undefined) row.customer_name = j.customerName;
  if (j.customerPhone !== undefined) row.customer_phone = j.customerPhone || "";
  if (j.customerEmail !== undefined) row.customer_email = j.customerEmail || "";
  if (j.customerAddress !== undefined) row.customer_address = j.customerAddress || "";
  if (j.trade !== undefined) row.trade = j.trade;
  if (j.stage !== undefined) row.stage = j.stage;
  if (j.contractAmount !== undefined) row.contract_amount = Number(j.contractAmount) || 0;
  if (j.startDate !== undefined) row.start_date = toIso(j.startDate);
  if (j.targetDate !== undefined) row.target_date = toIso(j.targetDate);
  if (j.notes !== undefined) row.notes = j.notes || "";
  return row;
};

const vendorFromRow = (r) => ({
  id: r.id,
  name: r.name,
  category: r.category,
  phone: r.phone || "",
  email: r.email || "",
  notes: r.notes || "",
  createdAt: toIso(r.created_at),
});

const vendorToRow = (v) => {
  const row = {};
  if (v.name !== undefined) row.name = v.name;
  if (v.category !== undefined) row.category = v.category;
  if (v.phone !== undefined) row.phone = v.phone || "";
  if (v.email !== undefined) row.email = v.email || "";
  if (v.notes !== undefined) row.notes = v.notes || "";
  return row;
};

const clientPaymentFromRow = (r) => ({
  id: r.id,
  amount: Number(r.amount || 0),
  date: toIso(r.payment_date),
  method: r.method,
  note: r.note || "",
});

const vendorPaymentFromRow = (r) => ({
  id: r.id,
  vendorName: r.vendor_name,
  category: r.category,
  amount: Number(r.amount || 0),
  date: toIso(r.payment_date),
  status: r.status,
  note: r.note || "",
});

/* ---------------------------------------------------------------------------
   Supabase implementation
   --------------------------------------------------------------------------- */

const unwrap = ({ data, error }) => {
  if (error) throw new Error(error.message || "Supabase request failed");
  return data;
};

const supabaseRepo = {
  mode: "supabase",

  async loadAll() {
    const [jobRows, vendorRows, cpRows, vpRows] = await Promise.all([
      supabase.from("jobs").select("*").order("number", { ascending: false }).then(unwrap),
      supabase.from("vendors").select("*").order("name", { ascending: true }).then(unwrap),
      supabase.from("client_payments").select("*").order("payment_date", { ascending: false }).then(unwrap),
      supabase.from("vendor_payments").select("*").order("payment_date", { ascending: false }).then(unwrap),
    ]);

    const jobs = jobRows.map(jobFromRow);
    const byId = new Map(jobs.map((j) => [j.id, j]));
    cpRows.forEach((r) => byId.get(r.job_id)?.clientPayments.push(clientPaymentFromRow(r)));
    vpRows.forEach((r) => byId.get(r.job_id)?.vendorPayments.push(vendorPaymentFromRow(r)));

    return { jobs, vendors: vendorRows.map(vendorFromRow) };
  },

  // Seeding is a database concern in Supabase mode, not something the browser
  // should ever do — a client-side seed would race between users.
  async replaceAll() {},

  async createJob(job) {
    // `number` is deliberately omitted: the job_number_seq sequence assigns it
    // server-side so concurrent creates can't land on the same job number.
    const row = await supabase
      .from("jobs")
      .insert({ id: job.id, ...jobToRow(job) })
      .select()
      .single()
      .then(unwrap);
    return jobFromRow(row);
  },

  async updateJob(id, patch) {
    await supabase.from("jobs").update(jobToRow(patch)).eq("id", id).then(unwrap);
  },

  async deleteJob(id) {
    // client_payments / vendor_payments cascade from the FK.
    await supabase.from("jobs").delete().eq("id", id).then(unwrap);
  },

  async createClientPayment(jobId, p) {
    await supabase
      .from("client_payments")
      .insert({
        id: p.id,
        job_id: jobId,
        amount: Number(p.amount) || 0,
        payment_date: toIso(p.date),
        method: p.method,
        note: p.note || "",
      })
      .then(unwrap);
  },

  async deleteClientPayment(_jobId, paymentId) {
    await supabase.from("client_payments").delete().eq("id", paymentId).then(unwrap);
  },

  async createVendorPayment(jobId, p) {
    // vendor_name is stored as a snapshot on the payment; vendor_id links to
    // the directory when a vendor of that name exists, and is simply null for
    // a one-off vendor typed straight into the payment form.
    const match = await supabase
      .from("vendors")
      .select("id")
      .eq("name", p.vendorName)
      .maybeSingle()
      .then(unwrap);

    await supabase
      .from("vendor_payments")
      .insert({
        id: p.id,
        job_id: jobId,
        vendor_id: match?.id ?? null,
        vendor_name: p.vendorName,
        category: p.category,
        amount: Number(p.amount) || 0,
        payment_date: toIso(p.date),
        status: p.status || "pending",
        note: p.note || "",
      })
      .then(unwrap);
  },

  async updateVendorPayment(_jobId, paymentId, patch) {
    const row = {};
    if (patch.status !== undefined) row.status = patch.status;
    if (patch.amount !== undefined) row.amount = Number(patch.amount) || 0;
    if (patch.category !== undefined) row.category = patch.category;
    if (patch.note !== undefined) row.note = patch.note || "";
    if (patch.date !== undefined) row.payment_date = toIso(patch.date);
    if (patch.vendorName !== undefined) row.vendor_name = patch.vendorName;
    await supabase.from("vendor_payments").update(row).eq("id", paymentId).then(unwrap);
  },

  async deleteVendorPayment(_jobId, paymentId) {
    await supabase.from("vendor_payments").delete().eq("id", paymentId).then(unwrap);
  },

  async createVendor(vendor) {
    await supabase.from("vendors").insert({ id: vendor.id, ...vendorToRow(vendor) }).then(unwrap);
  },

  async updateVendor(id, patch) {
    await supabase.from("vendors").update(vendorToRow(patch)).eq("id", id).then(unwrap);
  },

  async deleteVendor(id) {
    // vendor_payments.vendor_id is ON DELETE SET NULL — the payment history
    // survives with its vendor_name snapshot intact.
    await supabase.from("vendors").delete().eq("id", id).then(unwrap);
  },
};

/* ---------------------------------------------------------------------------
   localStorage fallback (dev only, when no Supabase env vars are present)
   --------------------------------------------------------------------------- */

let cache = null;

const persistLocal = () => localAdapter.set(LOCAL_KEY, JSON.stringify(cache)).catch(() => {});

const mapJob = (jobId, fn) => {
  cache.jobs = cache.jobs.map((j) => (j.id === jobId ? fn(j) : j));
  return persistLocal();
};

const localRepo = {
  mode: "local",

  async loadAll() {
    try {
      const res = await localAdapter.get(LOCAL_KEY);
      cache = res && res.value ? JSON.parse(res.value) : null;
    } catch {
      cache = null;
    }
    return cache;
  },

  async replaceAll(data) {
    cache = data;
    return persistLocal();
  },

  async createJob(job) {
    const next = (cache.jobs.reduce((m, j) => Math.max(m, Number(j.number) || 0), 1000)) + 1;
    const created = { ...job, number: next };
    cache.jobs = [created, ...cache.jobs];
    await persistLocal();
    return created;
  },
  async updateJob(id, patch) { return mapJob(id, (j) => ({ ...j, ...patch })); },
  async deleteJob(id) { cache.jobs = cache.jobs.filter((j) => j.id !== id); return persistLocal(); },

  async createClientPayment(jobId, p) {
    return mapJob(jobId, (j) => ({ ...j, clientPayments: [p, ...(j.clientPayments || [])] }));
  },
  async deleteClientPayment(jobId, paymentId) {
    return mapJob(jobId, (j) => ({ ...j, clientPayments: (j.clientPayments || []).filter((p) => p.id !== paymentId) }));
  },
  async createVendorPayment(jobId, p) {
    return mapJob(jobId, (j) => ({ ...j, vendorPayments: [p, ...(j.vendorPayments || [])] }));
  },
  async updateVendorPayment(jobId, paymentId, patch) {
    return mapJob(jobId, (j) => ({
      ...j,
      vendorPayments: (j.vendorPayments || []).map((p) => (p.id === paymentId ? { ...p, ...patch } : p)),
    }));
  },
  async deleteVendorPayment(jobId, paymentId) {
    return mapJob(jobId, (j) => ({ ...j, vendorPayments: (j.vendorPayments || []).filter((p) => p.id !== paymentId) }));
  },

  async createVendor(vendor) { cache.vendors = [vendor, ...cache.vendors]; return persistLocal(); },
  async updateVendor(id, patch) {
    cache.vendors = cache.vendors.map((v) => (v.id === id ? { ...v, ...patch } : v));
    return persistLocal();
  },
  async deleteVendor(id) { cache.vendors = cache.vendors.filter((v) => v.id !== id); return persistLocal(); },
};

export const repo = isSupabaseConfigured ? supabaseRepo : localRepo;
